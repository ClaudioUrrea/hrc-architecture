#!/usr/bin/env python3
"""Times of the chronology table (Table "chronology" of manuscript R4) from the queue log.

    python3 make_chronology.py --log /opt/work/queue4.log --out numbers/r4_chronology.tex

The queue log (queue4.sh) records every campaign start ("=== <campaign> start <UTC>") and the
output of the publication scripts, including GitHub's push time of every tag
("PUBLISHED tag=<t> object=<sha> github_pushed_at=<UTC>") and the local time at which each freeze
record committed through the GitHub API was confirmed ("published record <path> (<UTC>)").
Nothing is typed by hand; a time not yet in the log prints as a red "??".
"""
import argparse
import re
from datetime import datetime
from pathlib import Path

MISSING = r"\missingnum"
MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def parse(ts):
    return datetime.strptime(ts.rstrip("Z"), "%Y-%m-%dT%H:%M:%S")


def day_time(ts):
    d = parse(ts)
    return f"{d.day} {MON[d.month - 1]}, {d:%H:%M}"


def clock(ts):
    return f"{parse(ts):%H:%M:%S}"


def first(pattern, text):
    m = re.search(pattern, text, re.M)
    return m.group(1) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    t = Path(a.log).read_text(errors="replace") if Path(a.log).exists() else ""
    TS = r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ)"
    start = lambda c: first(rf"^=== {c} start {TS}", t)
    pushed = lambda tag: first(rf"PUBLISHED tag={re.escape(tag)} \S+ github_pushed_at={TS}", t)
    # GitHub server time of the commit of the record (RECORD line), not the queue-side confirmation time
    record = lambda p: first(rf"RECORD {re.escape(p)} commit=[0-9a-f]+ {TS}", t)
    m = {}
    m["ChrTuneStart"] = start("tuning")
    m["ChrCompareStart"] = start("compare")
    m["ChrTimingStart"] = start("timing")
    m["ChrProtocolStart"] = start("protocol bench")
    m["ChrReportTag"] = start("report")
    m["ChrMetricsFatal"] = first(rf"^=== FATAL {TS}: code_metrics", t)
    m["ChrMetricsDone"] = first(rf"^=== code metrics done {TS}", t)
    cp = pushed("campaign-v4-compare")
    m["ChrCompareTag"] = cp
    m["ChrComparePushed"] = cp
    m["ChrCompareRecord"] = record("docs/freeze/FREEZE_campaign-v4-compare.md")
    m["ChrReportPushed"] = pushed("campaign-v4-report")
    lines = ["% generated by scripts/make_chronology.py from " + a.log + " -- do not edit",
             r"\providecommand{\missingnum}{\textcolor{red}{??}}"]
    for k, v in sorted(m.items()):
        if v is None:
            s = MISSING
        elif k.endswith("Pushed") or k.endswith("Record"):
            s = clock(v)
        else:
            s = day_time(v)
        lines.append(f"\\newcommand{{\\{k}}}{{{s}}}")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"{sum(v is not None for v in m.values())}/{len(m)} chronology times found -> {a.out}")


if __name__ == "__main__":
    main()
