#!/usr/bin/env python3
"""Supplementary analyses for manuscript R4, added after the round-4 review of the text
(specified after the campaigns; not pre-registered). Nothing is read from the manuscript; no run is
modified; every run is read through analysis/hrc_logs.py, which verifies its manifest first.

    python3 supp_r4.py --repo /opt/work/hrc31 --runs /opt/work/hrc31/runs \
        --extra results_extra.json --out results_supp.json [--limit N]

  U1  stops of the QP chain (QP failed, limit conflict, final check): episodes from the logged
      controller_stop_begin/end events, their durations and rate; share of time at standstill per
      strategy (comparison) and the separations and barrier value in stop cycles (timing);
  U2  detected fault episodes of the timing campaign (pre-registered function faults._per_run, one
      run at a time): per-category run-bootstrap intervals of the rates, and constraint-violation
      episodes split into those that followed an injected lunge and those generated by the
      controller and the scripted operator, with the time they kept the cell stopped;
  U3  ablation by host load, with paired differences matched by seed and scenario;
  U4  stops actually executed by the robot model (timing campaign) compared with the robot terms of
      Eq. (3): path length of every link point from the stop command to standstill, from the logged
      joint positions and the repository's own kinematics (train/train_cbf.py: link_points);
  U5  service-affecting episodes by category in each fault-sensitivity run;
  U6  watchdog stops in the timing campaign.
"""
import argparse, json, sys
from collections import Counter, defaultdict
from pathlib import Path
import numpy as np

QP_STOP = ("qp_failed", "limit_conflict", "final_check_failed")


def q_stats(x):
    x = np.asarray(x, float)
    if x.size == 0:
        return None
    return {"n": int(x.size), "p5": float(np.percentile(x, 5)), "p50": float(np.median(x)),
            "p95": float(np.percentile(x, 95)), "max": float(x.max()), "mean": float(x.mean())}


def boot_rate(counts, hours, B=10000, seed=1):
    counts, hours = np.asarray(counts, float), np.asarray(hours, float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(counts), (B, len(counts)))
    r = counts[idx].sum(1) / hours[idx].sum(1)
    return [float(np.percentile(r, 2.5)), float(np.percentile(r, 97.5))]


def boot_median_diff(d, B=10000, seed=2):
    d = np.asarray(d, float)
    rng = np.random.default_rng(seed)
    m = np.median(d[rng.integers(0, len(d), (B, len(d)))], axis=1)
    return [float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))]


def stop_mask(H, c):
    m = np.zeros(len(c), bool)
    for f in QP_STOP:
        if f in H.FLAGS:
            m |= H.flag(c, f)
    return m


def stop_episodes(H, d):
    ev = sorted(H.events(d), key=lambda e: e["t_ns"])
    beg, out = None, []
    for e in ev:
        if e["text"] == "controller_stop_begin":
            beg = e["t_ns"]
        elif e["text"] == "controller_stop_end" and beg is not None:
            out.append((e["t_ns"] - beg) * 1e-9)
            beg = None
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True); ap.add_argument("--runs", required=True)
    ap.add_argument("--extra", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--limit", type=int, default=0)
    a = ap.parse_args()
    sys.path.insert(0, str(Path(a.repo) / "analysis")); sys.path.insert(0, str(Path(a.repo) / "train"))
    import hrc_logs as H
    import faults
    from train_cbf import load_dh, link_points
    dh = load_dh(Path(a.repo) / "cfg/robots/ur5e.json")
    out = {"note": __doc__.strip().splitlines()[0]}
    lim = (lambda L: L[:a.limit]) if a.limit else (lambda L: L)

    # ---------------- U1 (comparison, by strategy) ----------------
    U1c = {}
    for d in lim(H.runs(a.runs, "baseline_compare")):
        strat = H.config(d).get("control", {}).get("strategy") or d.name.split("_")[-2]
        c = H.cycles(d)
        w = np.diff(c["t_release_ns"].astype(np.int64), append=c["t_release_ns"][-1] + 20_000_000) * 1e-9
        s = U1c.setdefault(strat, {"time_s": 0.0, "standstill_s": 0.0, "stop_cycles": 0, "cycles": 0, "episodes": []})
        s["time_s"] += float(w.sum()); s["standstill_s"] += float(w[c["qd_meas_norm"] < 1e-3].sum())
        s["stop_cycles"] += int(stop_mask(H, c).sum()); s["cycles"] += len(c)
        s["episodes"] += stop_episodes(H, d)
    out["U1_compare"] = {k: {"standstill_share": v["standstill_s"] / v["time_s"], "qp_stop_share": v["stop_cycles"] / v["cycles"],
                             "episodes": len(v["episodes"]), "episodes_per_h": len(v["episodes"]) / (v["time_s"] / 3600),
                             "duration_s": q_stats(v["episodes"])} for k, v in U1c.items()}

    # ---------------- U1 (timing) + U4 + U6 ----------------
    T = {"time_s": 0.0, "episodes": [], "h": [], "sep_est": [], "sep_true": [], "stop_cycles": 0, "cycles": 0}
    U4 = []
    U6 = Counter()
    timing = lim(H.runs(a.runs, "timing_campaign"))
    for d in timing:
        c = H.cycles(d)
        T["time_s"] += float((c["t_release_ns"][-1] - c["t_release_ns"][0]) * 1e-9)
        T["episodes"] += stop_episodes(H, d)
        sm = stop_mask(H, c)
        T["stop_cycles"] += int(sm.sum()); T["cycles"] += len(c)
        idx = np.nonzero(sm)[0][::20]
        T["h"] += c["h_geo"][idx].tolist(); T["sep_est"] += c["min_sep_m"][idx].tolist(); T["sep_true"] += c["gt_min_sep_m"][idx].tolist()
        U6[d.name] = sum(1 for e in H.events(d) if e["text"] == "watchdog_stop" and e.get("src") == "watchdog")
        # U4: stop onsets with the robot moving, followed by stop cycles until standstill
        q = c["q"][:, :dh["n"]].astype(float); t = c["t_release_ns"].astype(np.int64) * 1e-9
        qm = c["qd_meas_norm"]
        onsets = np.nonzero(sm[1:] & ~sm[:-1])[0] + 1
        for k in onsets:
            if k < 2:
                continue
            P0, P1 = link_points(dh, q[k - 1:k]), link_points(dh, q[k:k + 1])
            v_r = float(np.linalg.norm(P1 - P0, axis=2).max() / (t[k] - t[k - 1]))
            if v_r < 0.02:
                continue
            j = k
            while j < len(c) and sm[j] and qm[j] >= 1e-3:
                j += 1
            if j >= len(c) or not sm[j]:
                continue  # stop released before standstill
            P = link_points(dh, q[k:j + 1])
            path = np.linalg.norm(np.diff(P, axis=0), axis=2).sum(0).max()
            S = v_r * 0.1 + v_r ** 2 / (2 * 1.2)
            U4.append((v_r, float(path), float(S), float(t[j] - t[k]), v_r / 1.2))
    out["U1_timing"] = {"episodes": len(T["episodes"]), "episodes_per_h": len(T["episodes"]) / (T["time_s"] / 3600),
                        "duration_s": q_stats(T["episodes"]), "qp_stop_share": T["stop_cycles"] / max(T["cycles"], 1),
                        "share_episodes_le_1_cycle": float(np.mean(np.asarray(T["episodes"]) <= 0.021)) if T["episodes"] else None,
                        "h_geo_in_stop": q_stats(T["h"]), "sep_est_in_stop": q_stats(T["sep_est"]), "sep_true_in_stop": q_stats(T["sep_true"])}
    if U4:
        A = np.array(U4)
        out["U4_logged_stops"] = {"n": int(len(A)), "v_r": q_stats(A[:, 0]), "path_over_Seq3": q_stats(A[:, 1] / A[:, 2]),
                                  "path_exceeds_Seq3": int((A[:, 1] > A[:, 2]).sum()),
                                  "braking_over_Teq3": q_stats(A[:, 3] / A[:, 4]),
                                  "braking_exceeds_Teq3": int((A[:, 3] > A[:, 4] + 0.02).sum()),
                                  "path_over_braking_term": q_stats(A[:, 1] / (A[:, 0] ** 2 / 2.4))}
    out["U6_watchdog_stops"] = {"total": int(sum(U6.values())), "blocks_with": int(sum(1 for v in U6.values() if v)),
                                "by_block": {k: v for k, v in U6.items() if v}}

    # ---------------- U2 (timing faults per category) ----------------
    runs_counts, hours, cv = [], [], {"after_injected_lunge": 0, "generated": 0, "stopped_s_injected": 0.0, "stopped_s_generated": 0.0}
    for d in timing:
        rows, eps, dur, _ = faults._per_run(d, 2.0)
        hours.append(dur / 3600)
        cnt = Counter(e["category"] for e in eps)
        for ep in eps:  # episode fields as returned by the pre-registered function
            if ep["category"] != "constraint_violation":
                continue
            inj = ep["injections"] > 0  # an injected lunge within the matching window or inside the episode
            cv["after_injected_lunge" if inj else "generated"] += 1
            cv["stopped_s_injected" if inj else "stopped_s_generated"] += ep["duration_s"] or 0.0
        runs_counts.append(cnt)
    cats = sorted({k for c in runs_counts for k in c})
    out["U2_rates_by_category"] = {k: {"episodes": int(sum(c.get(k, 0) for c in runs_counts)),
                                       "rate_per_h": sum(c.get(k, 0) for c in runs_counts) / sum(hours),
                                       "run_bootstrap_ci95": boot_rate([c.get(k, 0) for c in runs_counts], hours)} for k in cats}
    cv["exposure_h"] = float(sum(hours))
    cv["share_of_time_stopped_by_generated"] = cv["stopped_s_generated"] / (sum(hours) * 3600)
    out["U2_constraint_violation_split"] = cv

    # ---------------- U3 (ablation by load) ----------------
    e = json.loads(Path(a.extra).read_text())
    ar = e["ablation_runs"]
    by = defaultdict(list)
    for r in ar:
        by[(r["configuration"], r["load"])].append(r)
    U3 = {"by_configuration_and_load": {f"{k[0]}|{k[1]}": {"runs": len(v), "median_of_run_medians_ms": float(np.median([x["median_ms"] for x in v])),
                                                           "largest_max_ms": float(max(x["max_ms"] for x in v)),
                                                           "median_sd_release_ms": float(np.median([x["sd_release_ms"] for x in v]))}
                                        for k, v in sorted(by.items())}, "paired": {}}
    key = lambda r: (r["seed"], r["scenario"])
    for load in ("idle", "load"):
        idx = {cfg: {key(r): r for r in by.get((cfg, load), [])} for cfg in ("A0", "A1", "A2", "A2a", "A2b", "A2c", "A3")}
        for x, y in (("A3", "A0"), ("A1", "A3"), ("A2", "A3"), ("A2a", "A3"), ("A2b", "A3"), ("A2c", "A3")):
            ks = sorted(set(idx[x]) & set(idx[y]))
            dd = [(idx[x][k]["median_ms"] - idx[y][k]["median_ms"]) * 1000 for k in ks]
            dm = [(idx[x][k]["max_ms"] - idx[y][k]["max_ms"]) for k in ks]
            if dd:
                U3["paired"][f"{x}-{y}|{load}"] = {"n": len(dd), "median_diff_of_medians_us": float(np.median(dd)), "ci95_us": boot_median_diff(dd),
                                                     "median_diff_of_max_ms": float(np.median(dm)), "ci95_max_ms": boot_median_diff(dm)}
    out["U3_ablation_by_load"] = U3

    # ---------------- U5 (sensitivity runs) ----------------
    U5 = {}
    for d in lim(H.runs(a.runs, "fault_sensitivity")):
        rows, eps, dur, _ = faults._per_run(d, 2.0)
        U5[H.manifest(d)["variant"]] = {"injected": len(rows), "episodes_by_category": dict(Counter(x["category"] for x in eps)),
                                        "injected_by_category": dict(Counter(r["category"] for r in rows))}
    out["U5_sensitivity_episodes"] = U5

    Path(a.out).write_text(json.dumps(out, indent=1))
    print(json.dumps({k: (v if k in ("U1_timing", "U2_constraint_violation_split", "U6_watchdog_stops") else "...") for k, v in out.items()}, indent=1)[:4000])


if __name__ == "__main__":
    main()
