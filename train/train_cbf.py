#!/usr/bin/env python3
"""Train the learned barrier h_theta(q, p_h) and export it for the C++ runtime.

Everything here is generated by this script from a documented sampling procedure; nothing
is fitted to a target statistic. The script writes its own run directory:

    runs/<utc>_cbf_train/
        config.json        exact arguments
        model.json         weights in the format read by src/safety/learned_cbf.cpp
        metrics.json       held-out metrics, Lipschitz bounds, training curve
        dataset.npz        the exact training / held-out / gray-zone samples used
        manifest.json      versions, seed, durations
        MANIFEST.sha256

Target. The network regresses the clearance  y = clip(d_min - r_safety, -0.3, 1.0)  [m],
where d_min is the smallest distance between the robot's link capsules (same DH model,
link radius and sampling as src/kin/kinematics.cpp) and any of the 20 keypoints. Over-
estimating clearance is the unsafe error, so it is penalised `w_over` times more than
under-estimating it.

Usage:
    python3 train/train_cbf.py --robot cfg/robots/ur5e.json --n-train 40000 --n-test 10000 \
        --n-gray 5000 --epochs 200 --seed 20261012 [--backup DIR]
"""
import argparse
import hashlib
import json
import platform
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

KP = 20
R_SAFETY = 0.15


# ----------------------------------------------------------------------------- kinematics
def load_dh(path):
    j = json.loads(Path(path).read_text())
    return {
        "n": int(j["dof"]),
        "a": np.array(j["a"], float), "d": np.array(j["d"], float), "alpha": np.array(j["alpha"], float),
        "off": np.array(j.get("theta_offset", [0] * int(j["dof"])), float),
        "r": float(j.get("link_radius", 0.06)), "k": int(j.get("samples_per_link", 4)),
        "base": np.array(j.get("base", [0, 0, 0]), float), "model": j["model"],
    }


def link_points(dh, q):
    """q: (B, n) -> (B, P, 3) sampled link points, identical to Kinematics::update."""
    B = q.shape[0]
    X = np.tile(np.array([1.0, 0, 0]), (B, 1)); Y = np.tile(np.array([0, 1.0, 0]), (B, 1)); Z = np.tile(np.array([0, 0, 1.0]), (B, 1))
    o = np.tile(dh["base"], (B, 1))
    origins = [o.copy()]
    for i in range(dh["n"]):
        th = q[:, i] + dh["off"][i]
        ct, st = np.cos(th)[:, None], np.sin(th)[:, None]
        ca, sa = np.cos(dh["alpha"][i]), np.sin(dh["alpha"][i])
        Xn = X * ct + Y * st
        Yp = -X * st + Y * ct
        Yn = Yp * ca + Z * sa
        Zn = -Yp * sa + Z * ca
        o = o + Z * dh["d"][i] + Xn * dh["a"][i]
        X, Y, Z = Xn, Yn, Zn
        origins.append(o.copy())
    pts = []
    for i in range(dh["n"]):
        A, Bp = origins[i], origins[i + 1]
        if np.max(np.linalg.norm(Bp - A, axis=1)) < 1e-6 and np.min(np.linalg.norm(Bp - A, axis=1)) < 1e-6:
            continue
        for s in range(1, dh["k"] + 1):
            pts.append(A + (Bp - A) * (s / dh["k"]))
    return np.stack(pts, axis=1)


# ----------------------------------------------------------------------------- human sampling
OFFS = {  # body frame (forward, left, up), matching SimHuman::keypoints
    0: (0, 0, 1.70), 1: (0, 0, 1.50), 2: (0, 0.20, 1.45), 6: (0, -0.20, 1.45), 10: (0, 0, 1.25), 11: (0, 0, 1.00),
    12: (0, 0.10, 0.95), 16: (0, -0.10, 0.95), 13: (0.02, 0.10, 0.50), 17: (0.02, -0.10, 0.50),
    14: (0, 0.10, 0.08), 18: (0, -0.10, 0.08), 15: (0.12, 0.10, 0.02), 19: (0.12, -0.10, 0.02),
}


def sample_humans(rng, B, near_fraction=0.5):
    """Random standing operators facing the robot, arms anywhere from rest to full reach.
    A fraction `near_fraction` stands within 0.3-1.1 m of the base so that near-contact
    states are well represented; the rest within 0.35-2.6 m."""
    near = rng.uniform(0, 1, B) < near_fraction
    r = np.where(near, rng.uniform(0.3, 1.1, B), rng.uniform(0.35, 2.6, B))
    phi = rng.uniform(-np.pi, np.pi, B)
    base = np.stack([r * np.cos(phi), r * np.sin(phi), np.zeros(B)], 1)
    yaw = phi + rng.normal(0, 0.4, B)  # facing roughly towards the robot
    fwd = np.stack([-np.cos(yaw), -np.sin(yaw), np.zeros(B)], 1)
    left = np.stack([np.sin(yaw), -np.cos(yaw), np.zeros(B)], 1)
    up = np.array([0, 0, 1.0])
    kp = np.zeros((B, KP, 3))
    for k, (f, l, u) in OFFS.items():
        kp[:, k] = base + fwd * f + left * l + up * u
    for sh, el, wr, ha in ((2, 3, 4, 5), (6, 7, 8, 9)):
        reach = rng.uniform(0, 1, B)[:, None]
        target = base + fwd * rng.uniform(0.2, 0.75, B)[:, None] + left * rng.uniform(-0.4, 0.4, B)[:, None] + up * rng.uniform(0.7, 1.5, B)[:, None]
        rest = kp[:, sh] + fwd * 0.08 + up * -0.63
        hand = rest + (target - rest) * reach
        u = hand - kp[:, sh]
        L = np.maximum(np.linalg.norm(u, axis=1, keepdims=True), 1e-6)
        wrist = hand - u * (0.08 / L)
        elbow = (kp[:, sh] + wrist) / 2 + up * (-0.08 * (1 - reach) - 0.04)
        kp[:, el], kp[:, wr], kp[:, ha] = elbow, wrist, hand
    return kp + rng.normal(0, 0.01, kp.shape)


def clearance(dh, q, kp):
    P = link_points(dh, q)                         # (B, P, 3)
    d = np.linalg.norm(P[:, :, None, :] - kp[:, None, :, :], axis=-1) - dh["r"]
    return d.min(axis=(1, 2))


def make_set(dh, rng, B, qlo, qhi, chunk=5000, near_fraction=0.5):
    xs, ds = [], []
    for s in range(0, B, chunk):
        b = min(chunk, B - s)
        q = rng.uniform(qlo, qhi, (b, dh["n"]))
        kp = sample_humans(rng, b, near_fraction)
        ds.append(clearance(dh, q, kp))
        xs.append(np.concatenate([q, (kp - dh["base"]).reshape(b, -1)], 1))
    return np.concatenate(xs), np.concatenate(ds)


# ----------------------------------------------------------------------------- network
def leaky(x, a):
    return np.where(x > 0, x, a * x)


class MLP:
    def __init__(self, sizes, rng, alpha=0.01):
        self.alpha = alpha
        self.W = [rng.normal(0, np.sqrt(2.0 / sizes[i]), (sizes[i + 1], sizes[i])) for i in range(len(sizes) - 1)]
        self.b = [np.zeros(sizes[i + 1]) for i in range(len(sizes) - 1)]
        self.u = [rng.normal(size=w.shape[0]) for w in self.W]

    def forward(self, x):
        acts, pres = [x], []
        h = x
        for i, (W, b) in enumerate(zip(self.W, self.b)):
            z = h @ W.T + b
            pres.append(z)
            h = leaky(z, self.alpha) if i < len(self.W) - 1 else z
            acts.append(h)
        return h[:, 0], acts, pres

    def backward(self, acts, pres, gout):
        gW, gb = [None] * len(self.W), [None] * len(self.W)
        g = gout[:, None]
        for i in reversed(range(len(self.W))):
            if i < len(self.W) - 1:
                g = g * np.where(pres[i] > 0, 1.0, self.alpha)
            gW[i] = g.T @ acts[i]
            gb[i] = g.sum(0)
            g = g @ self.W[i]
        return gW, gb, g

    def spectral_project(self, iters=2):
        """Project every weight matrix onto ||W||_2 <= 1 (power iteration, persistent vectors)."""
        for i, W in enumerate(self.W):
            u = self.u[i]
            for _ in range(iters):
                v = W.T @ u; v /= np.linalg.norm(v) + 1e-12
                u = W @ v; u /= np.linalg.norm(u) + 1e-12
            self.u[i] = u
            sigma = float(u @ W @ v)
            if sigma > 1.0:
                self.W[i] = W / sigma

    def spectral_norms(self):
        return [float(np.linalg.norm(W, 2)) for W in self.W]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--robot", default="cfg/robots/ur5e.json")
    ap.add_argument("--n-train", type=int, default=40000)
    ap.add_argument("--n-test", type=int, default=10000)
    ap.add_argument("--n-gray", type=int, default=5000)
    ap.add_argument("--epochs", type=int, default=200)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--hidden", type=int, default=128)
    ap.add_argument("--layers", type=int, default=3)
    ap.add_argument("--w-over", type=float, default=4.0)
    ap.add_argument("--out-scale", type=float, default=1.0)
    ap.add_argument("--gray-band", type=float, default=0.15)
    ap.add_argument("--near-fraction", type=float, default=0.5)
    ap.add_argument("--seed", type=int, default=20261012)
    ap.add_argument("--run-root", default="runs")
    ap.add_argument("--backup", action="append", default=[])
    args = ap.parse_args()

    t_start = time.time()
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%S.%f")[:-3] + "Z"
    out = Path(args.run_root) / f"{stamp}_cbf_train"
    out.mkdir(parents=True)
    (out / "config.json").write_text(json.dumps(vars(args), indent=2))

    dh = load_dh(args.robot)
    rng = np.random.default_rng(args.seed)
    qlo = np.array([-np.pi] + [-np.pi] * (dh["n"] - 1))
    qhi = -qlo
    Xtr, Dtr = make_set(dh, rng, args.n_train, qlo, qhi, near_fraction=args.near_fraction)
    Xte, Dte = make_set(dh, rng, args.n_test, qlo, qhi, near_fraction=args.near_fraction)
    # gray-zone set: samples whose true clearance lies within the gray band of the floor
    Xg, Dg = [], []
    while sum(len(d) for d in Dg) < args.n_gray:
        x, d = make_set(dh, rng, 20000, qlo, qhi, near_fraction=args.near_fraction)
        m = np.abs(d - R_SAFETY) < args.gray_band
        Xg.append(x[m]); Dg.append(d[m])
    Xg = np.concatenate(Xg)[: args.n_gray]; Dg = np.concatenate(Dg)[: args.n_gray]
    target = lambda d: np.clip(d - R_SAFETY, -0.3, 1.0)
    Ytr, Yte, Yg = target(Dtr), target(Dte), target(Dg)
    np.savez_compressed(out / "dataset.npz", X_train=Xtr, d_train=Dtr, X_test=Xte, d_test=Dte, X_gray=Xg, d_gray=Dg)

    mean = Xtr.mean(0)
    scale = Xtr.std(0) + 1e-6
    norm = lambda X: (X - mean) / scale
    sizes = [Xtr.shape[1]] + [args.hidden] * args.layers + [1]
    net = MLP(sizes, rng)
    # Adam
    mW = [np.zeros_like(w) for w in net.W]; vW = [np.zeros_like(w) for w in net.W]
    mb = [np.zeros_like(b) for b in net.b]; vb = [np.zeros_like(b) for b in net.b]
    b1, b2, eps, step = 0.9, 0.999, 1e-8, 0
    Xn = norm(Xtr)
    curve = []
    # hold out 10 % of the training set for early stopping (the test set is never used for selection)
    nval = len(Xn) // 10
    perm = rng.permutation(len(Xn))
    val_idx, tr_idx = perm[:nval], perm[nval:]
    best, best_state, patience = np.inf, None, 0
    for ep in range(args.epochs):
        rng.shuffle(tr_idx)
        for s in range(0, len(tr_idx), args.batch):
            idx = tr_idx[s: s + args.batch]
            pred, acts, pres = net.forward(Xn[idx])
            pred = pred * args.out_scale
            err = pred - Ytr[idx]
            w = np.where(err > 0, args.w_over, 1.0)
            gout = 2 * w * err / len(idx) * args.out_scale
            gW, gb, _ = net.backward(acts, pres, gout)
            step += 1
            for i in range(len(net.W)):
                mW[i] = b1 * mW[i] + (1 - b1) * gW[i]; vW[i] = b2 * vW[i] + (1 - b2) * gW[i] ** 2
                mb[i] = b1 * mb[i] + (1 - b1) * gb[i]; vb[i] = b2 * vb[i] + (1 - b2) * gb[i] ** 2
                net.W[i] -= args.lr * (mW[i] / (1 - b1 ** step)) / (np.sqrt(vW[i] / (1 - b2 ** step)) + eps)
                net.b[i] -= args.lr * (mb[i] / (1 - b1 ** step)) / (np.sqrt(vb[i] / (1 - b2 ** step)) + eps)
            net.spectral_project()
        pv, _, _ = net.forward(Xn[val_idx])
        ev = pv * args.out_scale - Ytr[val_idx]
        vloss = float(np.mean(np.where(ev > 0, args.w_over, 1.0) * ev ** 2))
        curve.append({"epoch": ep, "val_loss": vloss})
        if vloss < best - 1e-6:
            best, patience = vloss, 0
            best_state = ([w.copy() for w in net.W], [b.copy() for b in net.b])
        else:
            patience += 1
            if patience >= 25:
                break
        if ep % 10 == 0:
            print(f"epoch {ep:4d} val_loss {vloss:.6f}", flush=True)
    net.W, net.b = best_state

    # ------------------------------------------------------------- evaluation (held-out set, never used above)
    def predict(X):
        return net.forward(norm(X))[0] * args.out_scale
    pte = predict(Xte)
    unsafe = Dte < R_SAFETY
    safe = Dte >= R_SAFETY + args.gray_band
    trusted = np.abs(pte) >= args.gray_band
    # the unsafe error: a state below the floor that the trusted model calls safe
    false_safe = unsafe & trusted & (pte > 0)
    false_unsafe = safe & trusted & (pte < 0)
    pg = predict(Xg)
    # Lipschitz: certified upper bound vs. largest gradient norm found by search
    sn = net.spectral_norms()
    L_cert = float(np.prod(sn) * args.out_scale * np.max(1.0 / scale))
    def grad_norm(X):
        p, acts, pres = net.forward(norm(X))
        _, _, gx = net.backward(acts, pres, np.ones(len(X)) * args.out_scale)
        return np.linalg.norm(gx / scale, axis=1), gx / scale
    g0, _ = grad_norm(Xte)
    Xs = Xte[np.argsort(-g0)[:200]].copy()
    for _ in range(100):  # gradient ascent on the gradient norm (finite-difference direction)
        gn, gx = grad_norm(Xs)
        Xs += 0.01 * gx / (np.linalg.norm(gx, axis=1, keepdims=True) + 1e-12)
    L_search = float(max(g0.max(), grad_norm(Xs)[0].max()))

    def wilson(k, n, z=1.96):
        if n == 0:
            return [None, None]
        p = k / n; den = 1 + z * z / n; c = (p + z * z / (2 * n)) / den
        h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
        return [c - h, c + h]

    metrics = {
        "n_train": int(len(tr_idx)), "n_val": int(nval), "n_test": int(len(Xte)), "n_gray": int(len(Xg)),
        "epochs_run": len(curve), "best_val_loss": best,
        "test_mae_m": float(np.mean(np.abs(pte - Yte))),
        "test_unsafe": int(unsafe.sum()),
        "false_safe_rate_given_unsafe": float(false_safe.sum() / max(1, unsafe.sum())),
        "false_safe_wilson95": wilson(int(false_safe.sum()), int(unsafe.sum())),
        "false_unsafe_rate_given_safe": float(false_unsafe.sum() / max(1, safe.sum())),
        "abstention_rate_test": float(1 - trusted.mean()),
        "abstention_rate_gray": float(np.mean(np.abs(pg) < args.gray_band)),
        "lipschitz_certified_upper_bound": L_cert,
        "lipschitz_search_lower_bound": L_search,
        "spectral_norms": sn,
        "curve": curve,
    }
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    model = {
        "format": "hrc-mlp-v1", "robot": dh["model"], "input": "q[0..n-1] (rad), keypoints relative to robot base (m)",
        "target": "clip(d_min - 0.15, -0.3, 1.0) m", "leaky_alpha": net.alpha, "out_scale": args.out_scale,
        "x_mean": mean.tolist(), "x_scale": scale.tolist(),
        "layers": [{"W": W.tolist(), "b": b.tolist()} for W, b in zip(net.W, net.b)],
    }
    (out / "model.json").write_text(json.dumps(model))
    manifest = {
        "experiment": "cbf_train", "data_kind": "samples generated by this script from the stated sampling procedure; "
        "metrics computed on a held-out set never used for training or model selection",
        "start_utc": stamp, "duration_s": time.time() - t_start, "python": sys.version, "numpy": np.__version__,
        "platform": platform.platform(), "robot_file_sha256": hashlib.sha256(Path(args.robot).read_bytes()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    lines = []
    for f in sorted(out.iterdir()):
        if f.name != "MANIFEST.sha256":
            lines.append(f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.name}")
    (out / "MANIFEST.sha256").write_text("\n".join(lines) + "\n")
    for b in args.backup:
        shutil.copytree(out, Path(b) / out.name)
    print(json.dumps({k: v for k, v in metrics.items() if k != "curve"}, indent=2))
    print(f"run directory: {out}")


if __name__ == "__main__":
    main()
